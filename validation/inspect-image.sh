#!/usr/bin/env bash
# What three independent implementations make of an image: the Linux kernel's
# vfat driver (a read-only loop mount), mtools (mcopy, mdir) and dosfstools.
#
#   inspect-image.sh IMG...
#
# Runs as root INSIDE the Linux test VM (see scripts/vm-setup.sh). For each IMG
# it writes IMG.inspect beside it, one record per line, fields separated by
# TABs (paths are relative to the root, with no leading slash):
#
#   fsck_exit N                   fsck.fat -n IMG (0 = clean), then
#   fsck_output LINE              its output
#   kernel_mount ok|failed        the vfat mount (iocharset=utf8,tz=UTC,shortname=winnt)
#   kernel d|f SIZE MTIME BIRTH ATIME SHA256 PATH
#                                 each entry the kernel shows; times in epoch
#                                 seconds (fractions kept; BIRTH is the FAT
#                                 creation time); SHA256 is "-" for a directory
#   mtools_exit N                 mcopy -s -n -m ::/ to a directory, then
#   mtools d|f SIZE MTIME SHA256 PATH   each entry mtools copied out
#   mdir_exit N                   mdir -i IMG ::
#
# Images are generated by the Rust tests (and by generate.sh); nothing here is
# committed but this recipe.
set -uo pipefail

[ "$#" -gt 0 ] || { echo "usage: inspect-image.sh IMG..." >&2; exit 2; }
work="$(mktemp -d /var/tmp/fatinspect.XXXXXX)"
mnt="$work/mnt"
mkdir "$mnt"
cleanup() {
    cd /
    if mountpoint -q "$mnt"; then umount "$mnt" || true; fi
    rm -rf "${work:?}"
}
trap cleanup EXIT

# manifest DIR PREFIX: one record per entry under DIR.
manifest_kernel() {
    (cd "$1" && find . -mindepth 1 -print0 | LC_ALL=C sort -z | while IFS= read -r -d '' p; do
        p="${p#./}"
        if [ -d "$p" ] && [ ! -L "$p" ]; then
            printf 'kernel\td\t0\t%s\t%s\t%s\t-\t%s\n' "$(stat -c %.3Y "$p")" "$(stat -c %.3W "$p")" "$(stat -c %X "$p")" "$p"
        else
            printf 'kernel\tf\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(stat -c %s "$p")" "$(stat -c %.3Y "$p")" "$(stat -c %.3W "$p")" "$(stat -c %X "$p")" "$(sha256sum <"$p" | cut -d' ' -f1)" "$p"
        fi
    done)
}

for img in "$@"; do
    out="$img.inspect"
    : >"$out"
    rc=0
    text="$(fsck.fat -n "$img" 2>&1)" || rc=$?
    printf 'fsck_exit\t%s\n' "$rc" >>"$out"
    printf '%s\n' "$text" | sed 's/^/fsck_output\t/' >>"$out"

    local_img="$work/image"
    cp --sparse=always "$img" "$local_img"
    if mount -o ro,loop,iocharset=utf8,tz=UTC,shortname=winnt "$local_img" "$mnt" 2>"$work/mount.err"; then
        printf 'kernel_mount\tok\n' >>"$out"
        manifest_kernel "$mnt" >>"$out"
        umount "$mnt"
    else
        printf 'kernel_mount\tfailed\n' >>"$out"
        sed 's/^/mount_error\t/' "$work/mount.err" >>"$out"
    fi

    tree="$work/mtools-tree"
    rm -rf "${tree:?}"
    mkdir "$tree"
    rc=0
    TZ=UTC mcopy -i "$local_img" -s -n -m ::/ "$tree"/ 2>"$work/mcopy.err" || rc=$?
    printf 'mtools_exit\t%s\n' "$rc" >>"$out"
    sed 's/^/mtools_error\t/' "$work/mcopy.err" >>"$out"
    (cd "$tree" && find . -mindepth 1 -print0 | LC_ALL=C sort -z | while IFS= read -r -d '' p; do
        p="${p#./}"
        if [ -d "$p" ]; then
            printf 'mtools\td\t0\t%s\t-\t%s\n' "$(stat -c %Y "$p")" "$p"
        else
            printf 'mtools\tf\t%s\t%s\t%s\t%s\n' "$(stat -c %s "$p")" "$(stat -c %Y "$p")" "$(sha256sum <"$p" | cut -d' ' -f1)" "$p"
        fi
    done) >>"$out"
    rc=0
    mdir -i "$local_img" :: >"$work/mdir.txt" 2>&1 || rc=$?
    printf 'mdir_exit\t%s\n' "$rc" >>"$out"
    rm -f "$local_img"
done

{
    echo "kernel $(uname -r)"
    dpkg-query -W -f='${Package} ${Version}\n' dosfstools mtools coreutils
} >"$(dirname "$1")/tools.txt"
