# What Windows makes of a FAT volume the Rust driver wrote.
#
#   powershell -File windows-check.ps1 -Vhd NAME.vhd -Result NAME.result
#
# Runs INSIDE the Windows test VM (fs-windows-test-harness, reached through the
# fswth-local ssh host). Attaches the fixed VHD (a copy on the guest; a
# read-only attach shows no volume to the storage cmdlets), runs chkdsk on the
# volume without /F (a check that repairs nothing), lists every entry with its
# size, local last-write and creation times and SHA-256, and detaches the VHD.
# The result file is UTF-8, one record per line, fields separated by TABs:
#
#   chkdsk_exit N              chkdsk X: exit status (0 = no problems)
#   chkdsk_output LINE         its output
#   fs NAME                    the file system Windows recognised (FAT, FAT32)
#   label TEXT                 the volume label
#   entry d|f SIZE WRITE CREATED SHA256 PATH
#                              times are local, as FAT stores them
#
# Nothing here is committed but this recipe: the VHD is generated by the test.
param(
    [Parameter(Mandatory = $true)] [string]$Vhd,
    [Parameter(Mandatory = $true)] [string]$Result
)
$ErrorActionPreference = 'Stop'
$vhdPath = (Resolve-Path -LiteralPath $Vhd).Path
$lines = New-Object System.Collections.Generic.List[string]
$image = $null
try {
    $image = Mount-DiskImage -ImagePath $vhdPath -PassThru
    # The disk and its volume appear a moment after the attach returns.
    $volume = $null
    for ($try = 0; $try -lt 60 -and -not $volume; $try++) {
        $number = (Get-DiskImage -ImagePath $vhdPath).Number
        if ($null -ne $number) {
            $partition = Get-Partition -DiskNumber $number -ErrorAction SilentlyContinue |
                Where-Object { $_.DriveLetter } | Select-Object -First 1
            if ($partition) {
                $volume = Get-Volume -DriveLetter $partition.DriveLetter -ErrorAction SilentlyContinue
            }
        }
        if (-not $volume) { Start-Sleep -Milliseconds 500 }
    }
    if (-not $volume) { throw "no volume with a drive letter appeared for $vhdPath" }
    $letter = $volume.DriveLetter
    $lines.Add("fs`t$($volume.FileSystem)")
    $lines.Add("label`t$($volume.FileSystemLabel)")

    $log = Join-Path $env:TEMP "chkdsk-$letter.txt"
    $proc = Start-Process -FilePath chkdsk -ArgumentList "${letter}:" -NoNewWindow -PassThru -Wait -RedirectStandardOutput $log
    $lines.Add("chkdsk_exit`t$($proc.ExitCode)")
    foreach ($line in (Get-Content -LiteralPath $log)) { $lines.Add("chkdsk_output`t$line") }

    $root = "${letter}:\"
    $entries = Get-ChildItem -LiteralPath $root -Recurse -Force |
        Where-Object { $_.FullName -notlike "${letter}:\System Volume Information*" } |
        Sort-Object FullName
    foreach ($entry in $entries) {
        $relative = $entry.FullName.Substring($root.Length).Replace('\', '/')
        $write = $entry.LastWriteTime.ToString('yyyy-MM-ddTHH:mm:ss')
        $created = $entry.CreationTime.ToString('yyyy-MM-ddTHH:mm:ss.fff')
        if ($entry.PSIsContainer) {
            $lines.Add("entry`td`t0`t$write`t$created`t-`t$relative")
        } else {
            try {
                $hash = (Get-FileHash -LiteralPath $entry.FullName -Algorithm SHA256 -ErrorAction Stop).Hash.ToLower()
            } catch {
                $hash = 'unreadable'
            }
            $lines.Add("entry`tf`t$($entry.Length)`t$write`t$created`t$hash`t$relative")
        }
    }
} finally {
    if ($image) { Dismount-DiskImage -ImagePath $vhdPath | Out-Null }
    [System.IO.File]::WriteAllLines((Join-Path $PWD $Result), $lines, (New-Object System.Text.UTF8Encoding($false)))
}
